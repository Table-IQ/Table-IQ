//! The MongoDB MCP guard's attack tables, shared by `mongo_guard.rs` (the verdicts, no server)
//! and `mongo_mcp_live.rs` (the same texts over real HTTP against a real server, with the
//! database compared before and after).
//!
//! Adding a case: an attack goes in a REFUSE table; an ordinary read that merely looks like one
//! goes in an ALLOW table. A refused ALLOW row is a bug to investigate — never a reason to
//! relax the guard.

